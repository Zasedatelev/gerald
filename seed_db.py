def make_tickets(direction_slug: str) -> list[list[dict]]:
    """Генерирует 10 билетов по 5 вопросов для указанного направления.
       ЗАМЕНИТЕ содержимое реальными вопросами!
    """
    templates = QUESTION_BANK[direction_slug]
    # Нарезаем на билеты по 5 вопросов
    tickets = []
    for i in range(10):
        start = i * 5
        tickets.append(templates[start:start + 5])
    return tickets


