async def seed():
    conn = await asyncpg.connect(DATABASE_URL)
    try:
        # Применяем схему
        with open("schema.sql") as f:
            await conn.execute(f.read())

        for slug, title in DIRECTIONS:
            # Направление
            dir_id = await conn.fetchval(
                "INSERT INTO directions(slug, title) VALUES($1,$2) "
                "ON CONFLICT(slug) DO UPDATE SET title=EXCLUDED.title RETURNING id",
                slug, title,
            )
            questions_flat = QUESTION_BANK[slug]

            for ticket_num in range(1, 11):
                ticket_id = await conn.fetchval(
                    "INSERT INTO tickets(direction_id, number) VALUES($1,$2) "
                    "ON CONFLICT(direction_id, number) DO UPDATE SET number=EXCLUDED.number RETURNING id",
                    dir_id, ticket_num,
                )
                start = (ticket_num - 1) * 5
                for pos, q in enumerate(questions_flat[start:start + 5], start=1):
                    q_id = await conn.fetchval(
                        "INSERT INTO questions(ticket_id, position, text) VALUES($1,$2,$3) "
                        "ON CONFLICT(ticket_id, position) DO UPDATE SET text=EXCLUDED.text RETURNING id",
                        ticket_id, pos, q["text"],
                    )
                    # Удаляем старые варианты, вставляем новые
                    await conn.execute("DELETE FROM answers WHERE question_id=$1", q_id)
                    for i, opt in enumerate(q["options"]):
                        await conn.execute(
                            "INSERT INTO answers(question_id, text, is_correct) VALUES($1,$2,$3)",
                            q_id, opt, i == q["correct"],
                        )
            print(f"  ✓ {title} — 10 билетов заполнены")

        print("\nБаза данных заполнена успешно!")
    finally:
        await conn.close()


if __name__ == "__main__":
    asyncio.run(seed())
